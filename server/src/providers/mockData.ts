const timedWords = (
  lineId: string,
  entries: Array<[text: string, start: number, end: number]>,
): TranscriptWord[] =>
  entries.map(([text, start, end], index) => ({
    id: `${lineId}-word-${index + 1}`,
    text,
    start,
    end,
  }))

